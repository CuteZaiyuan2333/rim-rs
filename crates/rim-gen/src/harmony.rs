//! Typed Harmony hook: dominant-ingredient material carry.
//!
//! Vanilla resolves a made-from-stuff product's material via
//! `dominantIngredient.def` (`GenRecipe.MakeRecipeProducts`) and the dominant
//! ingredient is picked only among ingredients whose DEF is a stuff
//! (`Toils_Recipe.CalculateDominantIngredient`). A consumed MadeFromStuff
//! intermediate (a billet, a blade blank) is not itself a stuff def, so the
//! material chain's next hop would fall back to a default material.
//!
//! [`MaterialCarry`] generates a Harmony prefix that fixes this for the
//! owning mod's recipes: whenever the recipe's actual ingredients include one
//! of the registered intermediates, the dominant ingredient becomes a thin
//! `Thing` whose `def` is that intermediate's own `Stuff`; the vanilla
//! pipeline then continues unchanged (no product reconstruction, quality/art
//! untouched). The payload shape is the one proven in-game by Forge Expansion
//! (`-quicktest`).

use std::fmt::Write as _;

const DEFAULT_CLASS_NAME: &str = "MaterialCarry";
const DEFAULT_FILE_NAME: &str = "MaterialCarry.cs";

/// Builds a C# source file that patches
/// `Toils_Recipe.CalculateDominantIngredient` so a mod's MadeFromStuff
/// intermediates carry their material through the chain.
///
/// Attaching one to a [`ModBuilder`](crate::builder::ModBuilder) is equivalent
/// to hand-writing `src-csharp/MaterialCarry.cs` and passing it to
/// [`ModBuilder::csharp`](crate::builder::ModBuilder::csharp). The generated
/// code still needs the Harmony assembly reference, e.g.
/// `<game>/Mods/harmony/Current/Assemblies/0Harmony.dll` via
/// [`ModBuilder::csharp_reference`](crate::builder::ModBuilder::csharp_reference),
/// and the Harmony mod itself must load before this mod (see
/// [`ModBuilder::load_after`](crate::builder::ModBuilder::load_after)).
///
/// ```no_run
/// use rim_gen::prelude::*;
///
/// Mod::builder("Blade Expansion")
///     .package_id("me.blades")
///     .harmony_material_carry(
///         MaterialCarry::new("me.blades").intermediate("Kat_BladeBillet"),
///     )
///     .csharp_reference("/game/Mods/harmony/Current/Assemblies/0Harmony.dll");
/// ```
#[derive(Debug, Clone)]
pub struct MaterialCarry {
    harmony_id: String,
    class_name: String,
    namespace: Option<String>,
    file_name: String,
    intermediates: Vec<String>,
}

impl MaterialCarry {
    /// `harmony_id` is the Harmony instance id (`new Harmony(id)`); the mod's
    /// `packageId` is a good value.
    pub fn new(harmony_id: impl Into<String>) -> Self {
        Self {
            harmony_id: harmony_id.into(),
            class_name: DEFAULT_CLASS_NAME.to_string(),
            namespace: None,
            file_name: DEFAULT_FILE_NAME.to_string(),
            intermediates: Vec::new(),
        }
    }

    /// Registers an intermediate def: a MadeFromStuff resource whose `stuff`
    /// must be carried into downstream products (e.g. `Ham_Billet`).
    pub fn intermediate(mut self, def_name: impl Into<String>) -> Self {
        self.intermediates.push(def_name.into());
        self
    }

    /// Renames the generated static class (default `MaterialCarry`).
    pub fn class_name(mut self, class_name: impl Into<String>) -> Self {
        self.class_name = class_name.into();
        self
    }

    /// Wraps the generated class in a namespace (default: none).
    pub fn namespace(mut self, namespace: impl Into<String>) -> Self {
        self.namespace = Some(namespace.into());
        self
    }

    /// Renames the generated file (default `MaterialCarry.cs`); the `.cs`
    /// extension is appended when missing.
    pub fn file_name(mut self, file_name: impl Into<String>) -> Self {
        let mut name = file_name.into();
        if std::path::Path::new(&name).extension().is_none() {
            name.push_str(".cs");
        }
        self.file_name = name;
        self
    }

    pub fn file_name_ref(&self) -> &str {
        &self.file_name
    }

    /// The registered intermediate def names, in registration order.
    pub fn intermediates(&self) -> &[String] {
        &self.intermediates
    }

    /// Renders the complete C# source.
    pub fn source(&self) -> String {
        let class = &self.class_name;
        let harmony_id = &self.harmony_id;
        let indent = self.namespace.as_ref().map(|_| "    ").unwrap_or("");
        let intermediates = self.intermediates_literal();

        let mut code = String::with_capacity(4_096);
        let _ = write!(
            code,
            "// Generated by rim-rs (MaterialCarry): dominant-ingredient material carry.
//
// Vanilla picks a made-from-stuff product's material via the dominant
// ingredient's def (GenRecipe.MakeRecipeProducts), and the dominant
// ingredient is selected only among ingredients whose DEF is a stuff
// (Toils_Recipe.CalculateDominantIngredient). A consumed intermediate (a
// MadeFromStuff resource) is not a stuff def, so the material chain's next
// hop would lose the material. This prefix returns a thin Thing whose def is
// the consumed intermediate's own Stuff; everything else stays vanilla.

using System.Collections.Generic;
using System.Linq;
using HarmonyLib;
using Verse;
using Verse.AI;
"
        );

        if let Some(namespace) = &self.namespace {
            let _ = write!(code, "\nnamespace {namespace}\n{{\n");
        }

        let _ = write!(
            code,
            "{indent}[StaticConstructorOnStartup]
{indent}public static class {class}
{indent}{{
{indent}    private static readonly HashSet<RecipeDef> CarryRecipes = new HashSet<RecipeDef>();
{indent}    private static readonly HashSet<ThingDef> Intermediates = new HashSet<ThingDef>();

{indent}    static {class}()
{indent}    {{
{indent}        foreach (string defName in new[] {{ {intermediates} }})
{indent}        {{
{indent}            ThingDef intermediate = DefDatabase<ThingDef>.GetNamedSilentFail(defName);
{indent}            if (intermediate == null)
{indent}            {{
{indent}                Log.Error($\"[{harmony_id}] MaterialCarry: intermediate def '{{defName}}' not found.\");
{indent}            }}
{indent}            else
{indent}            {{
{indent}                Intermediates.Add(intermediate);
{indent}            }}
{indent}        }}
{indent}
{indent}        foreach (RecipeDef recipe in DefDatabase<RecipeDef>.AllDefs)
{indent}        {{
{indent}            if (recipe.ingredients != null && recipe.ingredients.Any(ingredient =>
{indent}                ingredient?.filter != null && Intermediates.Any(ingredient.filter.Allows)))
{indent}            {{
{indent}                CarryRecipes.Add(recipe);
{indent}            }}
{indent}        }}
{indent}
{indent}        var target = AccessTools.Method(typeof(Toils_Recipe), \"CalculateDominantIngredient\");
{indent}        if (target == null)
{indent}        {{
{indent}            Log.Error(\"[{harmony_id}] CalculateDominantIngredient not found; material chains will lose their stuff identity.\");
{indent}            return;
{indent}        }}
{indent}
{indent}        new Harmony(\"{harmony_id}\").Patch(
{indent}            target,
{indent}            prefix: new HarmonyMethod(typeof({class}), nameof(DominantIngredientPrefix)));
{indent}    }}
{indent}
{indent}    // Only intercepts recipes that consume a registered intermediate and
{indent}    // were actually provided one; everything else runs vanilla.
{indent}    private static bool DominantIngredientPrefix(Job job, List<Thing> ingredients, ref Thing __result)
{indent}    {{
{indent}        RecipeDef recipe = job?.RecipeDef;
{indent}        if (recipe == null || !CarryRecipes.Contains(recipe))
{indent}        {{
{indent}            return true;
{indent}        }}
{indent}
{indent}        var group = ingredients?
{indent}            .Where(t => t != null && t.def != null && Intermediates.Contains(t.def) && t.Stuff != null)
{indent}            .GroupBy(t => t.Stuff)
{indent}            .OrderByDescending(g => g.Sum(t => t.stackCount))
{indent}            .FirstOrDefault();
{indent}        if (group == null)
{indent}        {{
{indent}            return true;
{indent}        }}
{indent}
{indent}        // Only `def` is read by MakeRecipeProducts; a bare Thing suffices.
{indent}        __result = new Thing {{ def = group.Key }};
{indent}        return false;
{indent}    }}
{indent}}}"
        );

        if self.namespace.is_some() {
            let _ = write!(code, "\n}}");
        }

        code.push('\n');
        code
    }

    /// C# string-array initializer for the registered intermediates.
    fn intermediates_literal(&self) -> String {
        self.intermediates
            .iter()
            .map(|def_name| format!("\"{def_name}\""))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn carry() -> MaterialCarry {
        MaterialCarry::new("miquella.powerhammer").intermediate("Ham_Billet")
    }

    #[test]
    fn generates_the_patch_source() {
        let source = carry().source();

        for expected in [
            "[StaticConstructorOnStartup]",
            "public static class MaterialCarry",
            "CalculateDominantIngredient",
            "new Harmony(\"miquella.powerhammer\").Patch(",
            "DominantIngredientPrefix(Job job, List<Thing> ingredients, ref Thing __result)",
            "\"Ham_Billet\"",
            "__result = new Thing { def = group.Key };",
        ] {
            assert!(source.contains(expected), "missing: {expected}");
        }
    }

    #[test]
    fn namespaced_output_indents_the_class() {
        let source = carry()
            .namespace("ForgeExpansion")
            .source();
        assert!(source.contains("namespace ForgeExpansion\n{"));
        assert!(source.contains("    [StaticConstructorOnStartup]"));
        assert!(source.contains("    public static class MaterialCarry"));
        assert!(source.trim_end().ends_with('}'));
    }

    #[test]
    fn defaults_have_no_namespace_and_cs_suffix() {
        let carry = MaterialCarry::new("me.mod").intermediate("Ham_Billet");
        assert_eq!(carry.file_name_ref(), "MaterialCarry.cs");
        let source = carry.source();
        assert!(!source.contains("namespace "));
        assert!(source.starts_with("// Generated by rim-rs"));
    }

    #[test]
    fn file_name_appends_extension() {
        let carry = MaterialCarry::new("me.mod").file_name("Chain");
        assert_eq!(carry.file_name_ref(), "Chain.cs");
    }

    #[test]
    fn multiple_intermediates_render_as_list() {
        let carry = MaterialCarry::new("me.mod")
            .intermediate("Ham_Billet")
            .intermediate("Kat_BladeBillet");
        assert!(
            carry
                .source()
                .contains(r#"new[] { "Ham_Billet", "Kat_BladeBillet" }"#)
        );
    }
}
